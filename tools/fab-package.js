// Turns KiCad's BOM and position CSVs into JLCPCB-style assembly files, writes the fab notes and
// zips the Gerbers. Run from the repo root after the kicad-cli exports (see README, "Fabrication"):
//   node tools/fab-package.js [output dir, default: output/fab]
const fs = require("fs");
const path = require("path");
const { execFileSync } = require("child_process");

const OUT = process.argv[2] || "output/fab";
const NAME = "SNAP_Power_Controller_CN3163_v1.0";

// JLCPCB/LCSC parts, checked on jlcpcb.com on 2026-11-20 (stock and Basic/Extended can change; re-check
// before ordering). Basic parts wherever one fits: only D3, the connectors, U1, U2 and U3 are Extended.
// Keyed by the first reference of each BOM line.
const PARTS = {
  C1: ["C13585", "CL31A106KBHNNNE (Samsung), 10uF 50V X5R 1206"],
  C2: ["C13585", "CL31A106KBHNNNE (Samsung), 10uF 50V X5R 1206"],
  C6: ["C14663", "CC0603KRX7R9BB104 (YAGEO), 100nF 50V X7R"],
  D3: ["C12624", "KT-0603G (Hubei KENTO), green, 3.1V at 5mA"],
  D4: ["C2286", "KT-0603R (Hubei KENTO), red"],
  D5: ["C8598", "B5819W SL (Changjiang), 40V 1A, 0.6V max at 1A"],
  J1: ["C114130", "53047-0210 (Molex)"],
  J5: ["C114130", "53047-0210 (Molex)"],
  J6: ["C114130", "53047-0210 (Molex)"],
  J7: ["C32713268", "HX PZ2.54-1x2P ZZ (hanxia), 2.54mm 1x02 pin header"],
  J8: ["C32713268", "HX PZ2.54-1x2P ZZ (hanxia), 2.54mm 1x02 pin header"],
  J9: ["C504989", "53047-0410 (Molex)"],
  Q2: ["C15127", "AO3401A (Alpha & Omega)"],
  R1: ["C21190", "0603WAF1001T5E (UNI-ROYAL), 1k 1%"],
  R2: ["C22843", "0603WAF1501T5E (UNI-ROYAL), 1.5k 1%"],
  R3: ["C23162", "0603WAF4701T5E (UNI-ROYAL), 4.7k 1%"],
  R4: ["C25819", "0603WAF4702T5E (UNI-ROYAL), 47k 1%"],
  R6: ["C25334", "1206W4F100LT5E (UNI-ROYAL), 0.1R 1% thick film"],
  R8: ["C25804", "0603WAF1002T5E (UNI-ROYAL), 10k 1%"],
  U1: ["C559031", "CN3163 (Consonance)"],
  U2: ["C181255", "INA3221AIRGVR (TI)"],
  U3: ["C970558", "LDL1117S50R (ST)"],
};
const LCSC = Object.fromEntries(Object.entries(PARTS).map(([r, [c]]) => [r, c]));
const MPN = Object.fromEntries(Object.entries(PARTS).map(([r, [, m]]) => [r, m]));

function parseCsv(text) {
  return text.trim().split(/\r?\n/).map((line) => [...line.matchAll(/"([^"]*)"|([^,]+)/g)].map((m) => m[1] ?? m[2]));
}
const q = (v) => `"${String(v).replace(/"/g, '""')}"`;

// BOM: Comment, Designator, Footprint, LCSC Part #, Manufacturer Part
const [, ...bom] = parseCsv(fs.readFileSync(path.join(OUT, "bom-kicad.csv"), "utf8"));
const bomOut = [["Comment", "Designator", "Footprint", "LCSC Part #", "Manufacturer Part", "Qty"].map(q).join(",")];
for (const [value, refs, footprint, qty] of bom) {
  const first = refs.split(",")[0];
  bomOut.push([value, refs, footprint.split(":")[1], LCSC[first] || "", MPN[first] || "", qty].map(q).join(","));
}
fs.writeFileSync(path.join(OUT, `${NAME}_BOM.csv`), bomOut.join("\n") + "\n");

// CPL: Designator, Mid X, Mid Y, Layer, Rotation (same absolute coordinates as the Gerbers)
const [, ...pos] = parseCsv(fs.readFileSync(path.join(OUT, "pos-kicad.csv"), "utf8"));
const cplOut = [["Designator", "Val", "Package", "Mid X", "Mid Y", "Rotation", "Layer"].map(q).join(",")];
for (const [ref, val, pkg, x, y, rot, side] of pos) {
  if (ref.startsWith("H")) continue;  // mounting holes are not placed parts
  cplOut.push([ref, val, pkg, `${(+x).toFixed(4)}mm`, `${(+y).toFixed(4)}mm`, (+rot).toFixed(1), side === "top" ? "Top" : "Bottom"].map(q).join(","));
}
fs.writeFileSync(path.join(OUT, `${NAME}_CPL.csv`), cplOut.join("\n") + "\n");

// Order notes: the settings to pick on the board house's form, and assembly cautions.
fs.writeFileSync(path.join(OUT, "FAB_NOTES.txt"), `SNAP Power Controller CN3163 v1.0 (JaisorGadgets, Nov. 20, 2026) - fabrication notes

Upload: ${NAME}_gerbers.zip (Gerber X2 + Excellon drill, generated by KiCad 10.0.7)

PCB order settings
  Layers:            2
  Size:              36.4 x 23.6 mm (1 mm 45-degree corner chamfers)
  Material:          FR-4, 1.6 mm
  Copper weight:     1 oz outer
  Min track / space: 0.2 mm / 0.2 mm
  Vias:              0.6 mm / 0.3 mm, 0.5 mm / 0.3 mm and 0.8 mm / 0.4 mm drill, tented
  Plated holes:      0.5 mm (Micro JST 1.25 / PicoBlade headers), 1.0 mm (2.54 mm pin headers J7, J8)
  Non-plated holes:  4 x 2.2 mm (M2 mounting), in NPTH.drl
  Solder mask:       both sides (any colour)
  Silkscreen:        both sides (back carries the module ID, ratings, a no-warranty notice and I2C pin names)
  Surface finish:    HASL lead-free or ENIG
  Panelisation:      none; no castellations, no edge plating, no impedance control

Assembly (optional): top side only
  BOM: ${NAME}_BOM.csv   Placement: ${NAME}_CPL.csv (same coordinates as the Gerbers)
  - Every BOM line has an LCSC part number, checked on jlcpcb.com on Nov. 20, 2026. All are
    Basic parts except D3, the connectors, U1, U2 and U3. Re-check stock before ordering.
  - Check part rotation and polarity in the assembler's preview before ordering, especially
    U1 (CN3163, exposed pad), U3 (LDL1117S50R), U2 (INA3221, VQFN-16 with exposed pad), Q2, D5-D8 and the LEDs D3 (green) / D4 (red).
  - Through-hole parts: J1-J6 and J9 (Molex 53047 PicoBlade headers), J7 and J8 (2.54 mm pin headers).
    Hand-solder them, or order through-hole assembly.
  - H1-H4 are mounting holes, not parts (left out of the BOM and placement files).
  - JP1 (top, left edge, marked LED) is two bare pads joined by a copper trace, no part: leave it as made. It
    enables the status LEDs; the user cuts the trace to turn them off.
  - JP2 (top left, marked NTC) is two bare pads joined by a copper trace, no part: leave it as made. It turns the
    charger's battery temperature sensing off. To use a 10k B3950 NTC, cut the trace and solder the NTC to the pads.
`);

// Gerber + drill zip: the file the board house uploads.
const zip = path.join(OUT, `${NAME}_gerbers.zip`);
fs.rmSync(zip, { force: true });
execFileSync("C:/Program Files/KiCad/10.0/bin/python.exe", ["-c",
  `import zipfile, pathlib, sys
src, dst = pathlib.Path(sys.argv[1]), sys.argv[2]
with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
    for f in sorted(src.iterdir()):
        z.write(f, f.name)`, path.join(OUT, "gerbers"), zip]);
console.log(`wrote ${NAME}_BOM.csv (${bomOut.length - 1} lines), ${NAME}_CPL.csv (${cplOut.length - 1} parts), ${NAME}_gerbers.zip`);
